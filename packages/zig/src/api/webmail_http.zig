}

fn handleMessageList(server: *WebmailHttpServer, conn: *webmail_tls.Stream, arena: std.mem.Allocator, req: Request) !void {
    var sess = (try requireSession(server, conn, arena, req)) orelse return;
    defer sess.deinit(server.allocator);

    const folder = req.queryParam(arena, "folder") orelse "INBOX";
    const requested_page = @max(parseUintParam(req, arena, "page", 1), 1);
    const per_page = @max(@min(parseUintParam(req, arena, "per_page", server.config.messages_per_page), 200), 1);
    const query = req.queryParam(arena, "q") orelse "";
    const sender = req.queryParam(arena, "from") orelse "";
    if (query.len > 256 or sender.len > 256) return sendError(conn, arena, 400, "bad_request", "Search is too long");
    const after: ?i64 = if (req.queryParam(arena, "after")) |value| (std.fmt.parseInt(i64, value, 10) catch return sendError(conn, arena, 400, "bad_request", "Invalid start date")) else null;
    const before: ?i64 = if (req.queryParam(arena, "before")) |value| (std.fmt.parseInt(i64, value, 10) catch return sendError(conn, arena, 400, "bad_request", "Invalid end date")) else null;
    if (after != null and before != null and before.? < after.?) return sendError(conn, arena, 400, "bad_request", "End date precedes start date");
    const grouped = std.mem.eql(u8, req.queryParam(arena, "conversations") orelse "", "true");
    const rows = maildir.queryMessages(arena, server.db, sess.username, .{
        .folder = folder,
        .query = query,
        .sender = sender,
        .after = after,
        .before = before,
        .unread = std.mem.eql(u8, req.queryParam(arena, "unread") orelse "", "true"),
        .flagged = std.mem.eql(u8, req.queryParam(arena, "flagged") orelse "", "true"),
        .attachments = std.mem.eql(u8, req.queryParam(arena, "attachments") orelse "", "true"),
        .include_context = grouped,
    }) catch |err| {
        if (err == maildir.MaildirError.InvalidFolderName) return sendError(conn, arena, 400, "bad_request", "Invalid folder");
        return sendError(conn, arena, 500, "server_error", "Failed to read messages");
    };
    const grouped_rows: []const threads.Thread = if (grouped) try threads.group(arena, rows) else &.{};
    const total = if (grouped) grouped_rows.len else rows.len;
    const last_page = @max(total / per_page + @intFromBool(total % per_page > 0), 1);
    const page = @min(requested_page, last_page);
    const start = (page - 1) * per_page;
    const end = @min(start + per_page, total);
    var matching: usize = 0;
    for (rows) |row| if (row.matches_filters) {
        matching += 1;
    };

    var body: std.ArrayList(u8) = .empty;
    const w = jw(&body, arena);
    try w.writeAll("{\"folder\":");
    try writeJsonString(w, folder);
    try w.print(",\"page\":{d},\"total\":{d},\"message_total\":{d},\"conversations\":{},\"items\":[", .{ page, total, matching, grouped });
    const msgs = if (grouped) &[_]maildir.MessageSummary{} else rows[start..end];
    for (msgs, 0..) |m, i| {
        if (i > 0) try w.writeAll(",");
        try writeMessageSummary(w, m);
    }
    try w.writeAll("],\"threads\":[");
    if (grouped) for (grouped_rows[start..end], 0..) |thread, index| {
        if (index > 0) try w.writeAll(",");
        try w.writeAll("{\"id\":");
        try writeJsonString(w, thread.id);
        try w.print(",\"count\":{d},\"unread\":{d},\"matching\":{d},\"latest\":", .{ thread.members.len, thread.unread, thread.matching });
        try writeMessageSummary(w, thread.latest);
        try w.writeAll(",\"members\":[");
        for (thread.members, 0..) |member, member_index| {
            if (member_index > 0) try w.writeAll(",");
            try writeMessageSummary(w, member);
        }
        try w.writeAll("]}");
    };
    try w.writeAll("]}");
    try sendJson(conn, arena, 200, body.items, null);
}

/// GET /webmail/api/search?q=...[&folder=...] — full-text search over the
/// session user's mail via the Typesense index. Hits are joined back to
/// IMAP UIDs so the frontend can open them with the existing message API.
fn handleSearch(server: *WebmailHttpServer, conn: *webmail_tls.Stream, arena: std.mem.Allocator, req: Request) !void {
    var sess = (try requireSession(server, conn, arena, req)) orelse return;
    defer sess.deinit(server.allocator);

    const q = req.queryParam(arena, "q") orelse "";
    if (q.len == 0) return sendError(conn, arena, 400, "bad_request", "Missing query parameter 'q'");
    if (!typesense.enabled()) return sendError(conn, arena, 503, "unavailable", "Search engine not configured");

    const folder = req.queryParam(arena, "folder");

    const hits = typesense.searchDocs(arena, sess.username, folder, q) catch {
        return sendError(conn, arena, 502, "search_failed", "Search engine error");
    };

    var body: std.ArrayList(u8) = .empty;
    const w = jw(&body, arena);
    try w.writeAll("{\"query\":");
    try writeJsonString(w, q);
    try w.writeAll(",\"items\":[");
    var written: usize = 0;
    for (hits) |hit| {
        // Join back to the message's IMAP UID; a hit whose file vanished
        // since indexing is dropped (the nightly reindex prunes the doc).
        const uid = (server.db.getUidForFile(sess.username, hit.mailbox, hit.filename) catch null) orelse continue;
        if (written > 0) try w.writeAll(",");
        written += 1;
        try w.print("{{\"uid\":{d},\"folder\":", .{uid});
        try writeJsonString(w, hit.mailbox);
        try w.writeAll(",\"subject\":");
        try writeJsonString(w, hit.subject);
        try w.writeAll(",\"from\":");
        try writeJsonString(w, hit.sender);
        try w.writeAll(",\"to\":");
        try writeJsonString(w, hit.recipients);
        try w.print(",\"date\":{d}}}", .{hit.date});
    }
    try w.writeAll("]}");
    try sendJson(conn, arena, 200, body.items, null);
}

