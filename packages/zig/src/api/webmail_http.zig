fn mapMaildirError(conn: *webmail_tls.Stream, arena: std.mem.Allocator, err: anyerror) !void {
    return switch (err) {
        maildir.MaildirError.MessageNotFound => sendError(conn, arena, 404, "not_found", "Message not found"),
